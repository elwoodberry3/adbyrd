/**
 * Splits an ES module into top-level declarations (with their leading
 * comments), keyed by name. Import lines and the file header are dropped and
 * `export` keywords removed, so chunks can be pasted into a Code node.
 */
export function chunkModule(src) {
  const lines = src.split("\n");
  // Drop the file's leading doc comment
  if (lines[0]?.startsWith("/**")) {
    while (lines.length && !lines[0].includes("*/")) lines.shift();
    lines.shift();
  }
  const chunks = new Map();
  let current = null;
  let pending = [];
  let inComment = false;
  for (const line of lines) {
    if (/^import\s/.test(line)) continue;
    const decl = line.match(/^(?:export\s+)?(?:async\s+)?(?:const|let|function)\s+([A-Za-z0-9_$]+)/);
    if (decl) {
      current = { name: decl[1], lines: [...pending, line.replace(/^export\s+/, "")] };
      chunks.set(current.name, current);
      pending = [];
      continue;
    }
    // Top-level comments (column 0) belong to the declaration that follows them
    if (inComment || /^(\/\*|\/\/)/.test(line)) {
      pending.push(line);
      inComment = line.startsWith("/*") ? !line.includes("*/") : inComment && !line.includes("*/");
      continue;
    }
    if (current) current.lines.push(...pending, line);
    pending = [];
  }
  return new Map([...chunks].map(([k, v]) => [k, v.lines.join("\n").replace(/\s+$/, "")]));
}

function pick(chunks, names, label) {
  return names
    .map((n) => {
      if (!chunks.has(n)) throw new Error(`${label}: no top-level declaration named ${n}`);
      return chunks.get(n);
    })
    .join("\n\n");
}

/* ---------------- node helpers ---------------- */

/** Deterministic UUID from a seed, so rebuilding produces an identical file. */
function uid(seed) {
  const h = createHash("sha1").update(seed).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

function cred(name) {
  return { id: null, name };
}

function node(wf, name, type, typeVersion, position, parameters, extra = {}) {
  return { parameters, id: uid(`${wf}/${name}`), name, type, typeVersion, position, ...extra };
}

function codeNode(wf, name, position, header, lib, body) {
  const jsCode = [
    `// ${header}`,
    "// GENERATED by automation/scripts/build-n8n-workflow.mjs. Edit the repo sources, not this node.",
    "",
    lib,
    "",
    "// ---- node logic ----",
    body.trim(),
    "",
  ].join("\n");
  return node(wf, name, "n8n-nodes-base.code", 2, position, { jsCode });
}

function ifNode(wf, name, position, leftValue, rightValue, op = { type: "string", operation: "equals" }) {
  return node(wf, name, "n8n-nodes-base.if", 2.2, position, {
    conditions: {
      options: { caseSensitive: true, leftValue: "", typeValidation: "loose", version: 2 },
      conditions: [{ id: uid(`${wf}/${name}/c`), leftValue, rightValue, operator: op }],
      combinator: "and",
    },
    options: {},
  });
}

function httpNode(wf, name, position, { method, url, auth, headers = [], jsonBody }) {
  const authParams =
    auth === "hubspot"
      ? { authentication: "predefinedCredentialType", nodeCredentialType: "hubspotAppToken" }
      : { authentication: "genericCredentialType", genericAuthType: "httpBearerAuth" };
  const credentials =
    auth === "hubspot" ? { hubspotAppToken: cred(CREDENTIALS.hubspot) } : { httpBearerAuth: cred(CREDENTIALS.resend) };
  return node(
    wf,
    name,
    "n8n-nodes-base.httpRequest",
    4.2,
    position,
    {
      method,
      url,
      ...authParams,
      sendHeaders: headers.length > 0,
      ...(headers.length ? { headerParameters: { parameters: headers } } : {}),
      sendBody: jsonBody !== undefined,
      ...(jsonBody !== undefined ? { specifyBody: "json", jsonBody } : {}),
      options: { response: { response: { fullResponse: true, neverError: true } }, timeout: 15000 },
    },
    // Network errors still come out as an item ({ error }) so the next Code node decides.
    { credentials, onError: "continueRegularOutput", alwaysOutputData: true },
  );
}

function waitNode(wf, name, position) {
  return node(wf, name, "n8n-nodes-base.wait", 1.1, position, { amount: "={{ $json.waitSeconds }}", unit: "seconds" }, { webhookId: uid(`${wf}/${name}/hook`) });
}

function configNode(wf, position, values) {
  return node(wf, "Config", "n8n-nodes-base.set", 3.4, position, {
    assignments: {
      assignments: Object.entries(values).map(([k, v]) => ({ id: uid(`${wf}/config/${k}`), name: k, value: v, type: "string" })),
    },
    options: {},
  });
}

/** connections helper: [from, to, outputIndex=0] */
function connect(pairs) {
  const out = {};
  for (const [from, to, idx = 0] of pairs) {
    out[from] ??= { main: [] };
    while (out[from].main.length <= idx) out[from].main.push([]);
    out[from].main[idx].push({ node: to, type: "main", index: 0 });
  }
  return out;
}

const sticky = (wf, name, position, content, width = 420, height = 260) =>
  node(wf, name, "n8n-nodes-base.stickyNote", 1, position, { content, width, height });

