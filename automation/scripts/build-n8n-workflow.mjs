export const serialize = (wf) => JSON.stringify(wf, null, 2) + "\n";

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes("--check");
  const outDirArg = process.argv.indexOf("--out-dir");
  const outDir = outDirArg > -1 ? path.resolve(process.argv[outDirArg + 1] ?? "") : null;
  if (outDir) await mkdir(outDir, { recursive: true });
  const built = await buildWorkflows();
  let stale = false;
  for (const key of ["main", "error"]) {
    const next = serialize(built[key]);
    const target = outDir ? path.join(outDir, path.basename(OUT[key])) : OUT[key];
    const current = await readFile(target, "utf8").catch(() => "");
    if (check) {
      if (current !== next) {
        stale = true;
        console.error(`out of date: ${path.relative(process.cwd(), target)}`);
      }
    } else {
      await writeFile(target, next);
      console.log(`${current === next ? "unchanged" : "wrote"} ${path.relative(process.cwd(), target)}`);
    }
  }
  if (stale) {
    console.error("Run: node automation/scripts/build-n8n-workflow.mjs");
    process.exit(1);
  }
}
